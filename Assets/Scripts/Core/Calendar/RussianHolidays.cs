using System;

namespace Schedule.Core.Calendar
{
    /// <summary>
    /// Нерабочие праздничные дни РФ по ст. 112 ТК — только фиксированные даты.
    /// Ежегодные переносы выходных правительство утверждает отдельным постановлением,
    /// здесь их нет: если 23 февраля выпало на субботу, отгул в понедельник не появится.
    /// </summary>
    public static class RussianHolidays
    {
        public static bool IsHoliday(DateTime date)
        {
            return (date.Month, date.Day) switch
            {
                (1, >= 1 and <= 6) => true, // новогодние каникулы
                (1, 7) => true,             // Рождество Христово
                (1, 8) => true,             // новогодние каникулы
                (2, 23) => true,            // День защитника Отечества
                (3, 8) => true,             // Международный женский день
                (5, 1) => true,             // Праздник Весны и Труда
                (5, 9) => true,             // День Победы
                (6, 12) => true,            // День России
                (11, 4) => true,            // День народного единства
                _ => false,
            };
        }
    }
}
